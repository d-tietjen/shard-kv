use super::{RedisCommandCase, RedisCommandFamily, RedisCommandParts, RedisCommandProfile};

const fn module_case(
    command_name: &'static str,
    parts: RedisCommandParts,
    setup: &'static [RedisCommandParts],
    expect_error: bool,
) -> RedisCommandCase {
    RedisCommandCase {
        family: RedisCommandFamily::Module,
        command_name,
        case_name: command_name,
        profile: RedisCommandProfile::Module,
        parts,
        script: &[],
        setup,
        expect_error,
        ignore_setup_error: true,
    }
}

